"""The MCP dashboard tools reach the default dashboard, and say when it stores nothing.

Home Assistant files the default dashboard under the key None, but the tools
looked it up as "lovelace": it was never found, and the error that should have
listed the dashboards crashed joining that None key, so the caller read
"sequence item 0: expected str instance, NoneType found". Once found, a default
dashboard nobody has taken control of stores no config, and its loader raises
ConfigNotFound with an empty message -- the write tools reported a failure with
no reason at all.

    pytest custom_components/config_auditor/tests/test_mcp_lovelace.py -v
"""
from __future__ import annotations

import sys
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import AsyncMock

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent.parent))

pytest.importorskip("homeassistant", reason="ConfigNotFound is Home Assistant's")

from homeassistant.components.lovelace.const import ConfigNotFound

from custom_components.config_auditor.mcp_server import tools_lovelace

STORED = {"title": "Home", "views": [{"title": "Main", "cards": [{"type": "markdown"}]}]}


def _dashboard(config=None, *, raises=None):
    load = AsyncMock(side_effect=raises) if raises else AsyncMock(return_value=config)
    return SimpleNamespace(async_load=load, async_save=AsyncMock())


def _hass(default, other=None, *, as_dict=False):
    """A hass whose lovelace data has the default dashboard under None.

    as_dict gives the dict HA kept there before the LovelaceData object.
    """
    dashboards = {None: default, "dashboard-ohana": other or _dashboard(STORED)}
    if as_dict:
        lovelace = {"mode": "storage", "dashboards": dashboards, "resources": None, "yaml_dashboards": {}}
    else:
        lovelace = SimpleNamespace(resource_mode="storage", dashboards=dashboards, resources=None, yaml_dashboards={})
    return SimpleNamespace(data={"lovelace": lovelace})


@pytest.mark.parametrize("as_dict", [False, True], ids=["object", "dict"])
class TestDefaultDashboard:
    @pytest.mark.asyncio
    @pytest.mark.parametrize("params", [{}, {"dashboard_id": "lovelace"}, {"dashboard_id": "default"}])
    async def test_default_ids_resolve_to_the_none_dashboard(self, as_dict, params):
        result = await tools_lovelace._tool_ha_get_lovelace(_hass(_dashboard(STORED), as_dict=as_dict), params)

        assert "error" not in result, result
        assert result["views_count"] == 1

    @pytest.mark.asyncio
    async def test_unknown_dashboard_lists_the_default_as_lovelace(self, as_dict):
        result = await tools_lovelace._tool_ha_get_lovelace(
            _hass(_dashboard(STORED), as_dict=as_dict), {"dashboard_id": "nope-dash"}
        )

        assert result["available_dashboards"] == ["lovelace", "dashboard-ohana"]
        assert "lovelace, dashboard-ohana" in result["suggestion"]

    @pytest.mark.asyncio
    async def test_custom_dashboard_still_resolves(self, as_dict):
        other = _dashboard({"views": []})
        result = await tools_lovelace._tool_ha_get_lovelace(
            _hass(_dashboard(STORED), other, as_dict=as_dict), {"dashboard_id": "dashboard-ohana"}
        )

        assert result["views_count"] == 0
        other.async_load.assert_awaited_once()


class TestAutoGeneratedDefault:
    @pytest.mark.asyncio
    async def test_read_says_nothing_is_stored(self):
        result = await tools_lovelace._tool_ha_get_lovelace(_hass(_dashboard(raises=ConfigNotFound)), {})

        assert "has no stored config" in result["error"]
        assert "Take control" in result["hint"]

    @pytest.mark.asyncio
    @pytest.mark.parametrize("tool, params", [
        ("_tool_ha_add_lovelace_card", {"card": {"type": "markdown", "content": "x"}}),
        ("_tool_ha_update_lovelace_card", {"card_index": 0, "card_config": {"type": "markdown"}}),
        ("_tool_ha_remove_lovelace_card", {"card_index": 0}),
    ])
    async def test_writes_say_nothing_is_stored_and_save_nothing(self, tool, params):
        default = _dashboard(raises=ConfigNotFound)

        result = await getattr(tools_lovelace, tool)(_hass(default), params)

        assert "has no stored config" in result["error"]
        default.async_save.assert_not_awaited()


@pytest.mark.asyncio
@pytest.mark.parametrize("as_dict", [False, True], ids=["object", "dict"])
async def test_list_dashboards_shows_the_default_once(as_dict):
    result = await tools_lovelace._tool_ha_list_dashboards(_hass(_dashboard(STORED), as_dict=as_dict), {})

    assert [d["url_path"] for d in result["dashboards"]] == ["lovelace", "dashboard-ohana"]
